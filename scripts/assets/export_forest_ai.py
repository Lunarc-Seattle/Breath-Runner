"""
Export pic/background.ai into web assets for the Forest · Level 1 game stage.

  assets/forest/background.jpg   full illustration with the interactive sprites removed
  assets/forest/runner.png       runner sprite (from the .ai)
  assets/forest/arrow.png        golden pacer arrow (from the .ai)
  assets/forest/coin.png         coin sprite (from the .ai)
  src/animation/forestMap.js     cliff-top profiles + coin / runner / arrow positions

The .ai is a PDF-compatible file, so PyMuPDF can read it directly:
  python3 -m pip install pymupdf
  python3 scripts/assets/export_forest_ai.py
"""
import json
from pathlib import Path

import pymupdf

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'pic' / 'background.ai'
OUT = ROOT / 'assets' / 'forest'
MAP_JS = ROOT / 'src' / 'animation' / 'forestMap.js'

BG_SCALE = 1.6          # 2436x1125 artboard -> ~3900px wide background
PROFILE_STEP = 4        # design px between cliff-top samples
CLIFF_FILL = (0.29, 0.38, 0.4)


def sprite_xrefs(page):
    """Identify sprites by their placed size: coins are 58px, arrow 124px, runner 2048px."""
    by_size = {}
    for info in page.get_image_info(xrefs=True):
        if info['xref']:
            by_size.setdefault((info['width'], info['height']), set()).add(info['xref'])
    pick = lambda w, h: next(iter(by_size[(w, h)]))
    return {'coin': pick(58, 58), 'arrow': pick(124, 124), 'runner': pick(2048, 2048)}


def save_sprite(doc, xref, path, max_px):
    pix = pymupdf.Pixmap(doc, xref)
    smask = doc.xref_get_key(xref, 'SMask')
    if smask[0] == 'xref':
        pix = pymupdf.Pixmap(pix, pymupdf.Pixmap(doc, int(smask[1].split()[0])))
    if max(pix.width, pix.height) > max_px:
        pix.shrink(max(0, (max(pix.width, pix.height) // max_px).bit_length() - 1))
    pix.save(path)


def sample_polygon(items, steps=24):
    pts = []
    for it in items:
        if it[0] == 'l':
            pts += [it[1], it[2]]
        elif it[0] == 'c':
            p0, p1, p2, p3 = it[1:5]
            for i in range(steps + 1):
                t = i / steps
                u = 1 - t
                pts.append(p0 * u**3 + p1 * 3 * u * u * t + p2 * 3 * u * t * t + p3 * t**3)
        elif it[0] == 're':
            r = it[1]
            pts += [r.tl, r.tr, r.br, r.bl]
    return [(p.x, p.y) for p in pts]


def top_profile(poly, x0, x1):
    """Topmost polygon edge at each sampled x (vertical-line / edge intersection)."""
    tops = []
    edges = list(zip(poly, poly[1:] + poly[:1]))
    x = x0
    while x <= x1:
        ys = [ay + (by - ay) * (x - ax) / (bx - ax)
              for (ax, ay), (bx, by) in edges
              if bx != ax and min(ax, bx) <= x <= max(ax, bx)]
        tops.append(round(min(ys), 1) if ys else None)
        x += PROFILE_STEP
    return tops


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    doc = pymupdf.open(SRC)
    page = doc[0]
    xrefs = sprite_xrefs(page)

    placements = {k: [] for k in xrefs}
    for info in page.get_image_info(xrefs=True):
        for name, xref in xrefs.items():
            if info['xref'] == xref:
                x0, y0, x1, y1 = info['bbox']
                placements[name].append({'x': round((x0 + x1) / 2), 'y': round((y0 + y1) / 2),
                                         'w': round(x1 - x0), 'h': round(y1 - y0), 'bottom': round(y1)})

    cliffs = []
    for d in page.get_drawings():
        fill = d.get('fill')
        if fill and all(abs(a - b) < 0.01 for a, b in zip(fill, CLIFF_FILL)):
            r = d['rect']
            x0 = max(0, int(r.x0) // PROFILE_STEP * PROFILE_STEP)
            x1 = min(int(page.rect.width), int(r.x1))
            tops = top_profile(sample_polygon(d['items']), x0, x1)
            cliffs.append({'x0': x0, 'tops': tops})
    cliffs.sort(key=lambda c: c['x0'])

    save_sprite(doc, xrefs['coin'], OUT / 'coin.png', 128)
    save_sprite(doc, xrefs['arrow'], OUT / 'arrow.png', 128)
    save_sprite(doc, xrefs['runner'], OUT / 'runner.png', 512)

    for xref in xrefs.values():
        page.delete_image(xref)
    pix = page.get_pixmap(matrix=pymupdf.Matrix(BG_SCALE, BG_SCALE), alpha=False)
    pix.save(OUT / 'background.jpg', jpg_quality=86)

    data = {
        'width': round(page.rect.width),
        'height': round(page.rect.height),
        'profileStep': PROFILE_STEP,
        'cliffs': cliffs,
        'coins': sorted(({'x': c['x'], 'y': c['y'], 'r': c['w'] / 2} for c in placements['coin']),
                        key=lambda c: c['x']),
        'runner': placements['runner'][0],
        'arrow': placements['arrow'][0],
    }
    MAP_JS.write_text(
        '// Generated by scripts/assets/export_forest_ai.py from pic/background.ai. Do not edit by hand.\n'
        f'export const FOREST_MAP = {json.dumps(data, ensure_ascii=False, separators=(",", ":"))};\n',
        encoding='utf-8')
    print(f'cliffs={len(cliffs)} coins={len(data["coins"])} -> {OUT}, {MAP_JS}')


if __name__ == '__main__':
    main()
